CREATE DATABASE IF NOT EXISTS minicnc CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE minicnc;

CREATE TABLE IF NOT EXISTS commands (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  username VARCHAR(128) NOT NULL,
  client_id VARCHAR(256) NOT NULL,
  device VARCHAR(64) NOT NULL,
  topic VARCHAR(255) NOT NULL,
  payload TEXT NOT NULL,
  allowed TINYINT(1) NOT NULL
);

CREATE TABLE IF NOT EXISTS images (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  username VARCHAR(128) NOT NULL,
  original_name VARCHAR(255) NOT NULL,
  mime VARCHAR(128) NOT NULL,
  size_bytes BIGINT UNSIGNED NOT NULL,
  sha256 CHAR(64) NOT NULL,
  file_path VARCHAR(512) NOT NULL,
  INDEX idx_images_sha256 (sha256)
);

CREATE TABLE IF NOT EXISTS status_log (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  device VARCHAR(64) NOT NULL,
  payload TEXT NOT NULL,
  INDEX idx_status_created_at (created_at)
);

CREATE TABLE IF NOT EXISTS dht_log (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  device VARCHAR(64) NOT NULL,
  temperature FLOAT NULL,
  humidity FLOAT NULL,
  chip_temperature FLOAT NULL,
  INDEX idx_dht_created_at (created_at)
);
